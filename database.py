import os
import sqlite3
from pathlib import Path
from typing import Any

import psycopg
from dotenv import load_dotenv
from psycopg.rows import dict_row
from sqlalchemy import create_engine, event
from sqlalchemy.engine import URL
from sqlalchemy.orm import declarative_base, sessionmaker


BASE_DIR = Path(__file__).resolve().parent
load_dotenv(BASE_DIR / ".env")

_configured_database_url = os.getenv("DATABASE_URL", "").strip()
if not _configured_database_url:
    if os.getenv("VERCEL") == "1":
        raise RuntimeError(
            "DATABASE_URL must be configured in Vercel before starting the API."
        )
    DATABASE_URL: str | URL = URL.create(
        "sqlite",
        database=str(BASE_DIR / "order_manager.db"),
    )
    DATABASE_URL_CONFIGURED = False
else:
    if _configured_database_url.startswith("postgres://"):
        _configured_database_url = _configured_database_url.replace(
            "postgres://", "postgresql+psycopg://", 1
        )
    elif _configured_database_url.startswith("postgresql://"):
        _configured_database_url = _configured_database_url.replace(
            "postgresql://", "postgresql+psycopg://", 1
        )
    DATABASE_URL = _configured_database_url
    DATABASE_URL_CONFIGURED = True

IS_POSTGRES = isinstance(DATABASE_URL, str) and DATABASE_URL.startswith(
    "postgresql+psycopg://"
)

engine_options: dict[str, Any] = {
    "pool_pre_ping": True,
    "pool_size": 1,
    "max_overflow": 0,
    "pool_timeout": 10,
    "pool_recycle": 300,
}
if IS_POSTGRES:
    engine_options["connect_args"] = {"application_name": "ai-order-manager"}
else:
    engine_options["connect_args"] = {
        "check_same_thread": False,
        "timeout": 10,
    }

engine = create_engine(DATABASE_URL, **engine_options)

if not IS_POSTGRES:

    @event.listens_for(engine, "connect")
    def _configure_sqlite_connection(
        dbapi_connection: sqlite3.Connection,
        _connection_record: Any,
    ) -> None:
        dbapi_connection.row_factory = sqlite3.Row
        cursor = dbapi_connection.cursor()
        cursor.execute("PRAGMA busy_timeout = 10000")
        cursor.execute("PRAGMA foreign_keys = ON")
        cursor.close()


SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
Base = declarative_base()
DB_ERRORS = (sqlite3.Error, psycopg.Error)


class _CursorAdapter:
    def __init__(self, connection: Any):
        if IS_POSTGRES:
            self._cursor = connection.driver_connection.cursor(row_factory=dict_row)
        else:
            self._cursor = connection.driver_connection.cursor()

    def execute(self, statement: str, parameters: Any = ()) -> "_CursorAdapter":
        self._cursor.execute(_adapt_statement(statement), parameters)
        return self

    def executemany(
        self, statement: str, parameters: Any
    ) -> "_CursorAdapter":
        self._cursor.executemany(_adapt_statement(statement), parameters)
        return self

    def __getattr__(self, name: str) -> Any:
        return getattr(self._cursor, name)


class _ConnectionAdapter:
    def __init__(self, connection: Any):
        self._connection = connection

    def cursor(self) -> _CursorAdapter:
        return _CursorAdapter(self._connection)

    def execute(self, statement: str, parameters: Any = ()) -> _CursorAdapter:
        return self.cursor().execute(statement, parameters)

    def executemany(
        self, statement: str, parameters: Any
    ) -> _CursorAdapter:
        return self.cursor().executemany(statement, parameters)

    def __getattr__(self, name: str) -> Any:
        return getattr(self._connection, name)


def _adapt_statement(statement: str) -> str:
    return statement.replace("?", "%s") if IS_POSTGRES else statement


def get_connection() -> _ConnectionAdapter:
    return _ConnectionAdapter(engine.raw_connection())


def begin_write_transaction(connection: _ConnectionAdapter) -> None:
    if not IS_POSTGRES:
        connection.execute("BEGIN IMMEDIATE")


def get_table_columns(
    connection: _ConnectionAdapter, table_name: str
) -> set[str]:
    if IS_POSTGRES:
        rows = connection.execute(
            """
            SELECT column_name
            FROM information_schema.columns
            WHERE table_schema = current_schema() AND table_name = ?
            """,
            (table_name,),
        ).fetchall()
        return {row["column_name"] for row in rows}

    rows = connection.execute(f"PRAGMA table_info({table_name})").fetchall()
    return {row[1] for row in rows}


def initialize_database(seed_default_products: bool = True) -> None:
    connection = get_connection()
    try:
        begin_write_transaction(connection)
        id_column = (
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            if IS_POSTGRES
            else "INTEGER PRIMARY KEY AUTOINCREMENT"
        )
        shopkeeper_id_type = "BIGINT" if IS_POSTGRES else "INTEGER"
        price_type = "DOUBLE PRECISION" if IS_POSTGRES else "REAL"

        connection.execute(
            f"""
            CREATE TABLE IF NOT EXISTS shopkeepers (
                id {id_column},
                name TEXT NOT NULL,
                shop_name TEXT NOT NULL,
                phone_number TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL UNIQUE,
                password TEXT NOT NULL,
                ai_calling_active INTEGER DEFAULT 1,
                created_at TEXT NOT NULL
            )
            """
        )
        connection.execute(
            f"""
            CREATE TABLE IF NOT EXISTS products (
                id {id_column},
                name TEXT NOT NULL UNIQUE,
                price {price_type} NOT NULL,
                stock INTEGER DEFAULT 0
            )
            """
        )
        connection.execute(
            f"""
            CREATE TABLE IF NOT EXISTS orders (
                id {id_column},
                customer_name TEXT NOT NULL,
                shopkeeper_id {shopkeeper_id_type},
                items TEXT NOT NULL,
                total {price_type} NOT NULL,
                status TEXT DEFAULT 'pending',
                created_at TEXT NOT NULL,
                FOREIGN KEY(shopkeeper_id) REFERENCES shopkeepers(id)
            )
            """
        )

        product_columns = get_table_columns(connection, "products")
        if "name" not in product_columns:
            connection.execute("ALTER TABLE products ADD COLUMN name TEXT")
        if "price" not in product_columns:
            connection.execute(
                f"ALTER TABLE products ADD COLUMN price {price_type} NOT NULL DEFAULT 0"
            )
        if "stock" not in product_columns:
            connection.execute(
                "ALTER TABLE products ADD COLUMN stock INTEGER NOT NULL DEFAULT 0"
            )

        order_columns = get_table_columns(connection, "orders")
        if "shopkeeper_id" not in order_columns:
            connection.execute(
                f"ALTER TABLE orders ADD COLUMN shopkeeper_id {shopkeeper_id_type} "
                "REFERENCES shopkeepers(id)"
            )

        connection.execute(
            "CREATE INDEX IF NOT EXISTS idx_orders_shopkeeper_id "
            "ON orders(shopkeeper_id)"
        )

        if seed_default_products:
            default_products = [
                ("Pizza", 250, 50),
                ("Burger", 120, 100),
                ("Coke", 50, 100),
                ("French Fries", 100, 80),
                ("Sandwich", 90, 70),
                ("Coffee", 80, 100),
                ("Pasta", 150, 60),
                ("Momos", 100, 80),
            ]
            for name, price, stock in default_products:
                connection.execute(
                    """
                    INSERT INTO products (name, price, stock)
                    SELECT ?, ?, ?
                    WHERE NOT EXISTS (
                        SELECT 1 FROM products WHERE LOWER(name) = LOWER(?)
                    )
                    ON CONFLICT(name) DO NOTHING
                    """,
                    (name, price, stock, name),
                )

        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
